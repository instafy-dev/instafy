#!/usr/bin/env node
// Regenerates Cub's no-WebGL stills (src/screens/landing/cub/landingCubFallback.ts)
// from the real landing page. Run it whenever Cub's pose, line or perch rules
// change, against a running dev server of this package:
//
//   pnpm dev                       # or any `vite` dev server for packages/frontend
//   node scripts/capture-cub-fallback.mjs [http://127.0.0.1:5173]
//
// For each perch (corner at 1440 px, header at 768 px, phone at 390 px) it
// opens the landing with reduced motion (Cub's calm frame) and asks the dev
// hooks (window.__cub, dev builds only) for three alpha-only WebP sprites at
// 2x: line art for light and dark, and body coverage. The engine recolours
// them with CSS masks. The corner still keeps his front arms hanging over the
// ledge (nothing of the window's chrome lies under them there); the header and
// phone stills use the capture pose (?cub-pose=fallback: no arm hangs over the
// window), since one still serves many widths and the coins and the phone
// bar's title move under him from one width to the next.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/screens/landing/cub/landingCubFallback.ts");
const base = (process.argv[2] || "http://127.0.0.1:5173").replace(/\/$/, "");

const PERCHES = [
  ["corner", 1440, 900],
  ["header", 768, 1024],
  ["mobile", 390, 844],
];
/** Perches captured without front arms (see above). */
const NO_FRONT_ARMS = new Set((process.env.CUB_FALLBACK_POSE ?? "header,mobile").split(",").filter(Boolean));

const browser = await chromium.launch();
const sprites = {};
try {
  for (const [mode, width, height] of PERCHES) {
    const mobile = width < 720;
    const context = await browser.newContext({
      viewport: { width, height },
      deviceScaleFactor: 2,
      isMobile: mobile,
      hasTouch: mobile,
      reducedMotion: "reduce",
      colorScheme: "light",
    });
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(`${base}/?cub-dev=0${NO_FRONT_ARMS.has(mode) ? "&cub-pose=fallback" : ""}`, { waitUntil: "networkidle" });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(
      () => window.__cub && window.__cub.dev && document.querySelector('[data-cub-gl="on"]'),
      null,
      { timeout: 30_000 },
    );
    await page.waitForTimeout(400);
    const sprite = await page.evaluate(() => window.__cub.dev.fbCapture(1.6));
    if (sprite.mode !== mode) throw new Error(`${width}px: expected the ${mode} perch, got ${sprite.mode}`);
    if (errors.length) throw new Error(`${width}px: ${errors.join("; ")}`);
    const round = (value) => Math.round(value * 10) / 10;
    sprites[mode] = {
      w: round(sprite.w),
      h: round(sprite.h),
      u: round(sprite.u),
      bx: round(sprite.bx),
      ey: round(sprite.ey),
      ink: sprite.ink,
      inkDark: sprite.inkDark,
      cov: sprite.cov,
    };
    const bytes = ["ink", "inkDark", "cov"].map((key) => Math.round((sprite[key].length * 3) / 4)).join(" / ");
    console.log(`${mode}: ${sprites[mode].w} x ${sprites[mode].h} css px, u ${sprites[mode].u}, ~${bytes} bytes`);
    await context.close();
  }
} finally {
  await browser.close();
}

const entry = (mode) => {
  const s = sprites[mode];
  return [
    `  ${mode}: {`,
    `    w: ${s.w},`,
    `    h: ${s.h},`,
    `    u: ${s.u},`,
    `    bx: ${s.bx},`,
    `    ey: ${s.ey},`,
    `    ink: "${s.ink}",`,
    `    inkDark: "${s.inkDark}",`,
    `    cov: "${s.cov}",`,
    "  },",
  ].join("\n");
};

writeFileSync(
  out,
  [
    "// Generated by scripts/capture-cub-fallback.mjs from the landing page. Do not edit.",
    "// Cub's no-WebGL stills: alpha-only WebP sprites at 2x (line art for light and",
    "// dark, body coverage), recoloured by the engine with CSS masks. Kept as text",
    "// and imported only when a visitor's browser cannot run the WebGL renderer.",
    "",
    'import type { CubFallbackSprites } from "./cubTypes";',
    "",
    "export const LANDING_CUB_FALLBACK: CubFallbackSprites = {",
    entry("corner"),
    entry("header"),
    entry("mobile"),
    "};",
    "",
  ].join("\n"),
);
console.log(`wrote ${out}`);

import octoHatchlingsGeometry from "../assets/octo-hatchlings.geometry.json";
import type { Hatchling } from "../utils/aiFace";

/**
 * One of Octo's hatchlings (docs/Brand.md, "Octo's hatchlings"): the face of
 * every AI without a picture of its own, a baby octopus in Octo's one ink.
 * `unknown` is the hollow face, for an AI the Studio knows only from text.
 *
 * Drawn like OctoMark: viewBox 0 0 64 64 in the mark's own frame, so it sits
 * at 75% of the tile exactly as the mark does (AiFace puts it there, on
 * Octo's tile), and filled with currentColor alone. The eyes are cut out of
 * the dome (even-odd), so the tile shows through them in both themes; the
 * hollow face is the reverse, its dome cut open the same way and its eyes
 * ink. The geometry is generated by scripts/generate-octo-hatchlings.mjs.
 *
 * Only Octo moves: a hatchling has no motion, and it never carries Octo's
 * hooks (data-octo-coin, .octo-mark). It is marked data-ai-face="hatchling".
 * Decorative: the face, or the name beside it, carries the accessible name.
 */
export function OctoHatchling({ face, className }: { face: Hatchling | "unknown"; className?: string }) {
  const { paths, circles } = octoHatchlingsGeometry.faces[face];
  return (
    <svg
      viewBox={octoHatchlingsGeometry.viewBox}
      className={className}
      aria-hidden="true"
      data-ai-face="hatchling"
      data-hatchling={face}
      xmlns="http://www.w3.org/2000/svg"
    >
      <g fill="currentColor">
        {paths.map((path, index) => (
          <path key={index} d={path.d} fillRule={path.fillRule === "evenodd" ? "evenodd" : undefined} />
        ))}
        {circles.map((circle, index) => (
          <circle key={index} cx={circle.cx} cy={circle.cy} r={circle.r} />
        ))}
      </g>
    </svg>
  );
}

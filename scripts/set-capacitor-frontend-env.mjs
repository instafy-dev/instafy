#!/usr/bin/env node
/**
 * Seed `packages/frontend/.env.production.local` for Capacitor builds.
 *
 * The iOS/Android apps bundle the Vite build output, so `VITE_*` values must be
 * present at build time. This script pulls hosted Supabase values from
 * `.env.supabase` (gitignored) and writes a minimal `.env.production.local`
 * file for the frontend package.
 *
 * NOTE: We intentionally do NOT write service-role keys here.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  resolvePrivateEnvPath,
  writePrivateEnvFileSync,
} from "./lib/privateEnvPaths.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "..");
const privateEnvPath = (relativePath) =>
  resolvePrivateEnvPath({ repoRoot, relativePath });
const frontendEnvPath = privateEnvPath("packages/frontend/.env.production.local");
const frontendLocalEnvPath = privateEnvPath("packages/frontend/.env.local");
const supabaseEnvPath = privateEnvPath(".env.supabase");
const supabaseLocalEnvPath = privateEnvPath(".env.supabase.local");
const localMode = trim(process.env.CAPACITOR_FRONTEND_ENV).toLowerCase() === "local";
const localHostIp = trim(process.env.CAPACITOR_FRONTEND_HOST_IP);
const disableLocalSpeechDefaults =
  trim(process.env.CAPACITOR_FRONTEND_DISABLE_LOCAL_SPEECH_DEFAULTS).toLowerCase() === "1" ||
  trim(process.env.CAPACITOR_FRONTEND_DISABLE_LOCAL_SPEECH_DEFAULTS).toLowerCase() === "true";
const localDefaultAnonKey =
  "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0";

const envPayload = localMode ? resolveLocalEnvPayload() : resolveHostedEnvPayload();

const lines = [
  `# Auto-generated by scripts/set-capacitor-frontend-env.mjs (${envPayload.mode} mode, gitignored).`,
  "# Do not commit this file.",
  "",
  `VITE_SUPABASE_URL=${envPayload.supabaseUrl}`,
  `VITE_SUPABASE_ANON_KEY=${envPayload.supabaseAnonKey}`,
  `VITE_CONTROLLER_URL=${envPayload.controllerUrl}`,
];

if (envPayload.transcriptionUrl) {
  lines.push(`VITE_INSTAFY_TRANSCRIPTION_URL=${envPayload.transcriptionUrl}`);
}
if (envPayload.transcriptionToken) {
  lines.push(`VITE_INSTAFY_TRANSCRIPTION_TOKEN=${envPayload.transcriptionToken}`);
}
if (envPayload.transcriptionModel) {
  lines.push(`VITE_INSTAFY_TRANSCRIPTION_MODEL=${envPayload.transcriptionModel}`);
}
if (envPayload.transcriptionLanguage) {
  lines.push(`VITE_INSTAFY_TRANSCRIPTION_LANGUAGE=${envPayload.transcriptionLanguage}`);
}
if (envPayload.synthesisUrl) {
  lines.push(`VITE_INSTAFY_SYNTHESIS_URL=${envPayload.synthesisUrl}`);
}
if (envPayload.synthesisToken) {
  lines.push(`VITE_INSTAFY_SYNTHESIS_TOKEN=${envPayload.synthesisToken}`);
}
if (envPayload.speechBaseUrl) {
  lines.push(`VITE_INSTAFY_SPEECH_BASE_URL=${envPayload.speechBaseUrl}`);
}
if (envPayload.speechToken) {
  lines.push(`VITE_INSTAFY_SPEECH_TOKEN=${envPayload.speechToken}`);
}
lines.push("");

try {
  const writtenPath = writePrivateEnvFileSync({
    repoRoot,
    relativePath: "packages/frontend/.env.production.local",
    data: lines.join("\n"),
    encoding: "utf-8",
  });
  if (writtenPath !== frontendEnvPath) {
    throw new Error("private env path changed between resolution and write");
  }
  console.log(`[set-capacitor-frontend-env] wrote ${frontendEnvPath} (${envPayload.mode} mode)`);
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`[set-capacitor-frontend-env] failed to write ${frontendEnvPath}: ${message}`);
  process.exit(1);
}

function trim(value) {
  return (value ?? "").toString().trim();
}

function isMeaningfulValue(value) {
  const trimmed = trim(value);
  if (!trimmed) {
    return false;
  }
  if (trimmed.includes("<your-project>")) {
    return false;
  }
  if (trimmed.includes("<hidden>")) {
    return false;
  }
  return true;
}

function pickFirstMeaningfulValue(...values) {
  for (const value of values) {
    if (isMeaningfulValue(value)) {
      return trim(value);
    }
  }
  return "";
}

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const env = {};
  const content = fs.readFileSync(filePath, "utf8");
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const idx = line.indexOf("=");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    const value = line
      .slice(idx + 1)
      .trim()
      .replace(/^['"](.+)['"]$/, "$1");
    if (!key || !value) continue;
    env[key] = value;
  }
  return env;
}

function resolveHostedEnvPayload() {
  const supabaseEnv = parseEnvFile(supabaseEnvPath);
  const frontendLocalEnv = parseEnvFile(frontendLocalEnvPath);
  const supabaseUrl = pickFirstMeaningfulValue(
    supabaseEnv.VITE_SUPABASE_URL,
    supabaseEnv.SUPABASE_URL,
  );
  const supabaseAnonKey = pickFirstMeaningfulValue(
    supabaseEnv.VITE_SUPABASE_ANON_KEY,
    supabaseEnv.SUPABASE_ANON_KEY,
  );
  const controllerUrl = pickFirstMeaningfulValue(supabaseEnv.VITE_CONTROLLER_URL) || "https://controller.instafy.dev";

  const missing = [];
  if (!supabaseUrl) missing.push("VITE_SUPABASE_URL");
  if (!supabaseAnonKey) missing.push("VITE_SUPABASE_ANON_KEY");

  if (missing.length > 0) {
    console.error(
      `[set-capacitor-frontend-env] Missing ${missing.join(", ")}; ensure ${supabaseEnvPath} is configured before syncing the mobile apps.`,
    );
    process.exit(1);
  }

  return {
    mode: "hosted",
    supabaseUrl,
    supabaseAnonKey,
    controllerUrl,
    speechBaseUrl: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_SPEECH_BASE_URL,
      frontendLocalEnv.VITE_INSTAFY_SPEECH_BASE_URL,
    ),
    speechToken: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_SPEECH_TOKEN,
      frontendLocalEnv.VITE_INSTAFY_SPEECH_TOKEN,
    ),
    transcriptionUrl: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_URL,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_URL,
    ),
    transcriptionToken: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_TOKEN,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_TOKEN,
    ),
    transcriptionModel: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_MODEL,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_MODEL,
    ),
    transcriptionLanguage: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_LANGUAGE,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_LANGUAGE,
    ),
    synthesisUrl: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_SYNTHESIS_URL,
      frontendLocalEnv.VITE_INSTAFY_SYNTHESIS_URL,
    ),
    synthesisToken: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_SYNTHESIS_TOKEN,
      frontendLocalEnv.VITE_INSTAFY_SYNTHESIS_TOKEN,
    ),
  };
}

function resolveLocalEnvPayload() {
  const frontendLocalEnv = parseEnvFile(frontendLocalEnvPath);
  const supabaseLocalEnv = parseEnvFile(supabaseLocalEnvPath);

  const defaultLocalSupabaseUrl = localHostIp
    ? `http://${localHostIp}:54321`
    : "http://127.0.0.1:54321";
  const defaultLocalControllerUrl = localHostIp
    ? `http://${localHostIp}:8788`
    : "http://127.0.0.1:8788";
  const defaultLocalSpeechTranscriptionUrl = localHostIp
    ? `http://${localHostIp}:8796/transcribe`
    : "http://127.0.0.1:8796/transcribe";
  const defaultLocalSpeechSynthesisUrl = localHostIp
    ? `http://${localHostIp}:8796/synthesize`
    : "http://127.0.0.1:8796/synthesize";

  const supabaseUrl = pickFirstMeaningfulValue(
    process.env.VITE_SUPABASE_URL,
    process.env.SUPABASE_URL,
    frontendLocalEnv.VITE_SUPABASE_URL,
    frontendLocalEnv.SUPABASE_URL,
    supabaseLocalEnv.VITE_SUPABASE_URL,
    supabaseLocalEnv.SUPABASE_URL,
  ) ||
    defaultLocalSupabaseUrl;

  const supabaseAnonKey = pickFirstMeaningfulValue(
    process.env.VITE_SUPABASE_ANON_KEY,
    process.env.SUPABASE_ANON_KEY,
    frontendLocalEnv.VITE_SUPABASE_ANON_KEY,
    frontendLocalEnv.SUPABASE_ANON_KEY,
    supabaseLocalEnv.VITE_SUPABASE_ANON_KEY,
    supabaseLocalEnv.SUPABASE_ANON_KEY,
  ) ||
    localDefaultAnonKey;

  const controllerUrl = pickFirstMeaningfulValue(
    process.env.VITE_CONTROLLER_URL,
    frontendLocalEnv.VITE_CONTROLLER_URL,
  ) ||
    defaultLocalControllerUrl;
  const speechBaseUrl = pickFirstMeaningfulValue(
    process.env.VITE_INSTAFY_SPEECH_BASE_URL,
    frontendLocalEnv.VITE_INSTAFY_SPEECH_BASE_URL,
    supabaseLocalEnv.VITE_INSTAFY_SPEECH_BASE_URL,
  );
  const explicitTranscriptionUrl = pickFirstMeaningfulValue(
    process.env.VITE_INSTAFY_TRANSCRIPTION_URL,
    frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_URL,
    supabaseLocalEnv.VITE_INSTAFY_TRANSCRIPTION_URL,
  );
  const explicitSynthesisUrl = pickFirstMeaningfulValue(
    process.env.VITE_INSTAFY_SYNTHESIS_URL,
    frontendLocalEnv.VITE_INSTAFY_SYNTHESIS_URL,
    supabaseLocalEnv.VITE_INSTAFY_SYNTHESIS_URL,
  );

  return {
    mode: "local",
    supabaseUrl,
    supabaseAnonKey,
    controllerUrl,
    speechBaseUrl,
    speechToken: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_SPEECH_TOKEN,
      frontendLocalEnv.VITE_INSTAFY_SPEECH_TOKEN,
      supabaseLocalEnv.VITE_INSTAFY_SPEECH_TOKEN,
    ),
    transcriptionUrl:
      explicitTranscriptionUrl ||
      (speechBaseUrl || disableLocalSpeechDefaults ? "" : defaultLocalSpeechTranscriptionUrl),
    transcriptionToken: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_TOKEN,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_TOKEN,
      supabaseLocalEnv.VITE_INSTAFY_TRANSCRIPTION_TOKEN,
    ),
    transcriptionModel: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_MODEL,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_MODEL,
      supabaseLocalEnv.VITE_INSTAFY_TRANSCRIPTION_MODEL,
    ),
    transcriptionLanguage: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_TRANSCRIPTION_LANGUAGE,
      frontendLocalEnv.VITE_INSTAFY_TRANSCRIPTION_LANGUAGE,
      supabaseLocalEnv.VITE_INSTAFY_TRANSCRIPTION_LANGUAGE,
    ),
    synthesisUrl:
      explicitSynthesisUrl ||
      (speechBaseUrl || disableLocalSpeechDefaults ? "" : defaultLocalSpeechSynthesisUrl),
    synthesisToken: pickFirstMeaningfulValue(
      process.env.VITE_INSTAFY_SYNTHESIS_TOKEN,
      frontendLocalEnv.VITE_INSTAFY_SYNTHESIS_TOKEN,
      supabaseLocalEnv.VITE_INSTAFY_SYNTHESIS_TOKEN,
    ),
  };
}
